def seed():
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        manufacturers_cache: dict[str, Manufacturer] = {
            mfr.name: mfr for mfr in db.query(Manufacturer).all()
        }
        added = updated = 0
        for mfr_name, country, model_name, year, powertrain, spec in CARS:
            mfr = manufacturers_cache.get(mfr_name)
            if mfr is None:
                mfr = Manufacturer(name=mfr_name, country=country)
                db.add(mfr)
                db.flush()
                manufacturers_cache[mfr_name] = mfr

            car = (
                db.query(CarModel)
                .filter_by(manufacturer_id=mfr.id, name=model_name, model_year=year)
                .one_or_none()
            )
            if car is None:
                car = CarModel(
                    manufacturer_id=mfr.id, name=model_name,
                    model_year=year, powertrain=powertrain,
                )
                db.add(car)
                db.flush()
                db.add(InfotainmentSpec(car_model_id=car.id, **spec))
                added += 1
            else:
                car.powertrain = powertrain
                if car.infotainment is None:
                    db.add(InfotainmentSpec(car_model_id=car.id, **spec))
                else:
                    for field, value in spec.items():
                        setattr(car.infotainment, field, value)
                updated += 1

        db.commit()
        print(f"Синхронизирани {len(CARS)} модела: {added} нови, {updated} обновени.")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
